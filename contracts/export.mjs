// Copies the compiled ABIs and the deployment addresses into packages/shared so
// the web app and the host node always talk to the contracts that were built.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "..", "packages", "shared", "src", "generated");
mkdirSync(outDir, { recursive: true });

const header = "// Generated by contracts/export.mjs — do not edit.\n";

const contracts = {
  gridMarketAbi: "GridMarket",
  swarmMarketAbi: "SwarmMarket",
  stakeRegistryAbi: "StakeRegistry",
  erc20Abi: "MockGRID",
};
let abiTs = header;
for (const [name, file] of Object.entries(contracts)) {
  const artifact = JSON.parse(readFileSync(join(here, "out", `${file}.sol`, `${file}.json`), "utf8"));
  abiTs += `export const ${name} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(outDir, "abi.ts"), abiTs);

const deployments = {};
const depDir = join(here, "deployments");
if (existsSync(depDir)) {
  for (const f of readdirSync(depDir)) {
    if (!f.endsWith(".json")) continue;
    deployments[Number(f.replace(".json", ""))] = JSON.parse(readFileSync(join(depDir, f), "utf8"));
  }
}
writeFileSync(
  join(outDir, "deployments.ts"),
  header +
    [
      "export type Deployment = {",
      "  GRID: `0x${string}`;",
      "  StakeRegistry: `0x${string}`;",
      "  GridMarket: `0x${string}`;",
      "  /** Absent on deployments made before swarm jobs existed. */",
      "  SwarmMarket?: `0x${string}`;",
      "};",
      "",
    ].join("\n") +
    `export const deployments: Record<number, Deployment> = ${JSON.stringify(deployments, null, 2)};\n`,
);

console.log(
  `exported ${Object.keys(contracts).length} ABIs and ${Object.keys(deployments).length} deployment(s) to packages/shared/src/generated`,
);
